/** UI order for the settings theme picker (presets only; custom lives under wallpaper). */
export const THEME_ORDER: Array<Exclude<AppThemeId, "custom">> = [
  "system",
  "cursor",
  "github-dark",
  "github-light",
  "ayaka-night",
  "ayaka-frost",
  "book",
  "inkwash",
  "worldcup",
  "graphite",
  "graphite-light",
  "midnight",
  "zinc",
];

export function getThemeDefinition(id: ResolvedThemeId): ThemeDefinition {
  return THEME_REGISTRY[id];
}

export function isResolvedThemeId(value: unknown): value is ResolvedThemeId {
  return typeof value === "string" && value in THEME_REGISTRY;
}
