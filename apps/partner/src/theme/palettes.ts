import { completeColorTokens, type ThemeColorInput, type ThemeColorTokens } from "./tokens.js";
import type { BuiltinWallpaperId } from "./wallpapers.js";

export type ResolvedThemeId =
  | "cursor"
  | "github-dark"
  | "github-light"
  | "graphite"
  | "graphite-light"
  | "midnight"
  | "zinc"
  | "book"
  | "inkwash"
  | "worldcup"
  | "ayaka-night"
  | "ayaka-frost";

export type AppThemeId = "system" | "custom" | ResolvedThemeId;

export interface ThemeDefinition {
  id: ResolvedThemeId;
  labelZh: string;
  labelEn: string;
  scheme: "light" | "dark";
  colors: ThemeColorTokens;
  /** Optional builtin wallpaper attached when wallpaperMode=theme */
  wallpaper?: BuiltinWallpaperId;
}

function theme(
  def: Omit<ThemeDefinition, "colors"> & { colors: ThemeColorInput },
): ThemeDefinition {
  return {
    ...def,
    colors: completeColorTokens(def.colors),
  };
}

