// ── parseGitDiff ─────────────────────────────────────────────────────────────

describe("parseGitDiff", () => {
  it("returns empty Map for empty input", () => {
    const result = parseGitDiff("");
    expect(result).toBeInstanceOf(Map);
    expect(result.size).toBe(0);
  });

  it("returns empty Map for whitespace-only input", () => {
    const result = parseGitDiff("  \n  ");
    expect(result).toBeInstanceOf(Map);
    expect(result.size).toBe(0);
  });

  it("parses single file with one hunk", () => {
    const stdout = [
      "diff --git a/src/index.ts b/src/index.ts",
      "--- a/src/index.ts",
      "+++ b/src/index.ts",
      "@@ -1,3 +1,4 @@",
      " unchanged",
      "-old line",
      "+new line",
      " still unchanged",
    ].join("\n");

    const result = parseGitDiff(stdout);
    expect(result.size).toBe(1);
    const hunks = result.get("src/index.ts");
    expect(hunks).toBeDefined();
    expect(hunks!.length).toBe(1);
    const hunk = hunks![0]!;
    expect(hunk.oldStart).toBe(1);
    expect(hunk.oldLines).toBe(3);
    expect(hunk.newStart).toBe(1);
    expect(hunk.newLines).toBe(4);
    expect(hunk.lines).toEqual([
      " unchanged",
      "-old line",
      "+new line",
      " still unchanged",
    ]);
  });

  it("parses multiple files with hunks", () => {
    const stdout = [
      "diff --git a/src/a.ts b/src/a.ts",
      "--- a/src/a.ts",
      "+++ b/src/a.ts",
      "@@ -1,2 +1,2 @@",
      " line1",
      "-old2",
      "+new2",
      "diff --git a/src/b.ts b/src/b.ts",
      "--- a/src/b.ts",
      "+++ b/src/b.ts",
      "@@ -10,3 +10,4 @@",
      " context",
      " more context",
      "+added line",
      " last context",
    ].join("\n");

    const result = parseGitDiff(stdout);
    expect(result.size).toBe(2);

    const hunksA = result.get("src/a.ts");
    expect(hunksA).toBeDefined();
    expect(hunksA!.length).toBe(1);

    const hunksB = result.get("src/b.ts");
    expect(hunksB).toBeDefined();
    expect(hunksB!.length).toBe(1);
  });

  it("skips binary files header", () => {
    const stdout = [
      "diff --git a/regular.ts b/regular.ts",
      "--- a/regular.ts",
      "+++ b/regular.ts",
      "@@ -1,1 +1,1 @@",
      "-old",
      "+new",
      "diff --git a/asset.png b/asset.png",
      "Binary files a/asset.png and b/asset.png differ",
    ].join("\n");

    const result = parseGitDiff(stdout);
    // Only the regular file should be included
    expect(result.size).toBe(1);
    expect(result.has("regular.ts")).toBe(true);
    expect(result.has("asset.png")).toBe(false);
  });

  it("skips 'index ...' lines", () => {
    const stdout = [
      "diff --git a/file.ts b/file.ts",
      "index abc123..def456 100644",
      "--- a/file.ts",
      "+++ b/file.ts",
      "@@ -1,1 +1,1 @@",
      "-old",
      "+new",
    ].join("\n");

    const result = parseGitDiff(stdout);
    expect(result.size).toBe(1);
    const hunks = result.get("file.ts");
    expect(hunks).toBeDefined();
    expect(hunks!.length).toBe(1);
    // The index line should not appear in the hunk lines
    expect(hunks![0]!.lines).toEqual(["-old", "+new"]);
  });

  it("skips '---' and '+++' lines", () => {
    const stdout = [
      "diff --git a/file.ts b/file.ts",
      "--- a/file.ts",
      "+++ b/file.ts",
      "@@ -1,1 +1,1 @@",
      "-old",
      "+new",
    ].join("\n");

    const result = parseGitDiff(stdout);
    const hunks = result.get("file.ts");
    expect(hunks![0]!.lines).toEqual(["-old", "+new"]);
  });

  it("skips 'new file' and 'deleted file' mode lines", () => {
    const stdout = [
      "diff --git a/new-file.ts b/new-file.ts",
      "new file mode 100644",
      "--- /dev/null",
      "+++ b/new-file.ts",
      "@@ -0,0 +1,2 @@",
      "+line1",
      "+line2",
    ].join("\n");

    const result = parseGitDiff(stdout);
    expect(result.size).toBe(1);
    const hunks = result.get("new-file.ts");
    expect(hunks![0]!.lines).toEqual(["+line1", "+line2"]);
  });

  it("skips 'old mode' and 'new mode' lines", () => {
    const stdout = [
      "diff --git a/script.sh b/script.sh",
      "old mode 100644",
      "new mode 100755",
      "--- a/script.sh",
      "+++ b/script.sh",
      "@@ -1,1 +1,1 @@",
      " unchanged",
    ].join("\n");

    const result = parseGitDiff(stdout);
    expect(result.size).toBe(1);
    const hunks = result.get("script.sh");
    expect(hunks![0]!.lines).toEqual([" unchanged"]);
  });

  it("parses hunk header with no count (defaults to 1)", () => {
    // @@ -1 +1 @@ means oldLines=1, newLines=1 (default when omitted)
    const stdout = [
      "diff --git a/file.ts b/file.ts",
      "--- a/file.ts",
      "+++ b/file.ts",
      "@@ -1 +1 @@",
      " unchanged",
    ].join("\n");

    const result = parseGitDiff(stdout);
    const hunks = result.get("file.ts")!;
    const hunk = hunks[0]!;
    expect(hunk.oldStart).toBe(1);
    expect(hunk.oldLines).toBe(1);
    expect(hunk.newStart).toBe(1);
    expect(hunk.newLines).toBe(1);
  });

  it("parses hunk header '@@ -1,5 +1,6 @@' correctly", () => {
    const stdout = [
      "diff --git a/file.ts b/file.ts",
      "--- a/file.ts",
      "+++ b/file.ts",
      "@@ -1,5 +1,6 @@",
      " context",
      "-old",
      "+new",
      " context",
    ].join("\n");

    const result = parseGitDiff(stdout);
    const hunk = result.get("file.ts")![0]!;
    expect(hunk.oldStart).toBe(1);
    expect(hunk.oldLines).toBe(5);
    expect(hunk.newStart).toBe(1);
    expect(hunk.newLines).toBe(6);
  });

  it("parses hunk header with large offsets", () => {
    const stdout = [
      "diff --git a/file.ts b/file.ts",
      "--- a/file.ts",
      "+++ b/file.ts",
      "@@ -1500,20 +1600,30 @@",
      " context line",
      "-removed line",
      "+added line one",
      "+added line two",
    ].join("\n");

    const result = parseGitDiff(stdout);
    const hunk = result.get("file.ts")![0]!;
    expect(hunk.oldStart).toBe(1500);
    expect(hunk.oldLines).toBe(20);
    expect(hunk.newStart).toBe(1600);
    expect(hunk.newLines).toBe(30);
  });

  it("caps files at MAX_FILES (50)", () => {
    const parts: string[] = [];
    for (let i = 0; i < 60; i++) {
      parts.push(`diff --git a/file${i}.ts b/file${i}.ts`);
      parts.push(`--- a/file${i}.ts`);
      parts.push(`+++ b/file${i}.ts`);
      parts.push("@@ -1,1 +1,1 @@");
      parts.push(` line${i}`);
    }
    const stdout = parts.join("\n");

    const result = parseGitDiff(stdout);
    expect(result.size).toBe(50);
  });

  it("includes empty lines in hunks", () => {
    const stdout = [
      "diff --git a/file.ts b/file.ts",
      "--- a/file.ts",
      "+++ b/file.ts",
      "@@ -1,3 +1,4 @@",
      " context",
      "-old",
      "+new",
      "",
    ].join("\n");

    const result = parseGitDiff(stdout);
    const hunk = result.get("file.ts")![0]!;
    // The empty line is just "" which is truthy check... wait, "" is falsy.
    // The source code checks: line.startsWith("+") || line.startsWith("-") || line.startsWith(" ") || line === ""
    // So empty lines ARE included in hunks (line === "")
    expect(hunk.lines).toContain("");
  });

  it("counts hunk lines within MAX_LINES_PER_FILE (400)", () => {
    // Create a diff where one file has exactly 400 hunk lines
    const lines: string[] = [];
    for (let i = 0; i < 410; i++) {
      lines.push(i % 2 === 0 ? `+added line ${i}` : ` context line ${i}`);
    }

    const stdout = [
      "diff --git a/large.ts b/large.ts",
      "--- a/large.ts",
      "+++ b/large.ts",
      "@@ -1,410 +1,410 @@",
      ...lines,
      "diff --git a/small.ts b/small.ts",
      "--- a/small.ts",
      "+++ b/small.ts",
      "@@ -1,1 +1,1 @@",
      " small",
    ].join("\n");

    const result = parseGitDiff(stdout);
    const largeHunk = result.get("large.ts")![0]!;
    // Should be capped at 400 lines
    expect(largeHunk.lines.length).toBeLessThanOrEqual(400);
    // The small file should still be parsed
    expect(result.has("small.ts")).toBe(true);
  });

  it("handles multiple hunks in a single file", () => {
    const stdout = [
      "diff --git a/multi.ts b/multi.ts",
      "--- a/multi.ts",
      "+++ b/multi.ts",
      "@@ -1,3 +1,3 @@",
      " line1",
      "-old2",
      "+new2",
      " line3",
      "@@ -10,3 +10,4 @@",
      " line10",
      "-removed11",
      "+added11",
      " line12",
      "+added13",
    ].join("\n");

    const result = parseGitDiff(stdout);
    expect(result.size).toBe(1);
    const hunks = result.get("multi.ts")!;
    expect(hunks.length).toBe(2);

    expect(hunks[0]!.oldStart).toBe(1);
    expect(hunks[1]!.oldStart).toBe(10);
  });

  it("skips file diffs without valid header match", () => {
    // A fileDiff that starts but has no `a/... b/...` header
    const stdout = [
      "diff --git a/valid.ts b/valid.ts",
      "--- a/valid.ts",
      "+++ b/valid.ts",
      "@@ -1,1 +1,1 @@",
      " line",
      "diff --git ",
      "garbage",
      "no header here",
    ].join("\n");

    const result = parseGitDiff(stdout);
    // Only valid.ts should be in the result
    expect(result.size).toBe(1);
    expect(result.has("valid.ts")).toBe(true);
  });

  it("handles diff without any hunks (only header)", () => {
    const stdout = [
      "diff --git a/header-only.ts b/header-only.ts",
      "index abc..def 100644",
      "--- a/header-only.ts",
      "+++ b/header-only.ts",
    ].join("\n");

    const result = parseGitDiff(stdout);
    // No hunks → file should not be in the result
    expect(result.size).toBe(0);
  });

  it("ignores lines that are not valid hunk lines after a hunk has started", () => {
    const stdout = [
      "diff --git a/file.ts b/file.ts",
      "--- a/file.ts",
      "+++ b/file.ts",
      "@@ -1,4 +1,4 @@",
      " context",
      "+added",
      "\\ No newline at end of file",
      " context",
    ].join("\n");

    const result = parseGitDiff(stdout);
    const hunk = result.get("file.ts")![0]!;
    // The \\ line should NOT be in the lines array (doesn't start with +, -, or space)
    expect(hunk.lines).toEqual([" context", "+added", " context"]);
  });
});

