import { vi, describe, it, expect, beforeEach } from "vitest";

// ── Hoisted mock state ──────────────────────────────────────────────────────

const { mockGitResponses, mockAccessResults } = vi.hoisted(() => {
  const mockGitResponses = new Map<
    string,
    { stdout: string; code: number }
  >();
  const mockAccessResults = new Map<string, boolean>();
  return { mockGitResponses, mockAccessResults };
});

// ── Mocks ────────────────────────────────────────────────────────────────────

vi.mock("node:child_process", () => ({
  execFile: vi.fn(
    (_file: string, args: string[], _options: unknown, callback: unknown) => {
      // For promisify: callback is the last argument auto-generated by util.promisify
      if (typeof callback === "function") {
        const key = args.join(" ");
        const response = mockGitResponses.get(key);
        if (response) {
          if (response.code === 0) {
            callback(null, { stdout: response.stdout }, "");
          } else {
            const err = Object.assign(new Error("git failed"), {
              code: response.code,
              stdout: response.stdout,
            });
            callback(err, "", "");
          }
        } else {
          // Default: command succeeds with empty stdout
          callback(null, { stdout: "" }, "");
        }
      }
    }
  ),
}));

vi.mock("node:fs/promises", () => ({
  access: vi.fn((path: string) => {
    if (mockAccessResults.get(path)) {
      return Promise.resolve();
    }
    return Promise.reject(Object.assign(new Error("ENOENT"), { code: "ENOENT" }));
  }),
}));

