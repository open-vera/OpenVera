// ── parseGitNumstat ──────────────────────────────────────────────────────────

describe("parseGitNumstat", () => {
  it("returns zero stats for empty input", () => {
    const result = parseGitNumstat("");
    expect(result.stats).toEqual({
      filesCount: 0,
      linesAdded: 0,
      linesRemoved: 0,
    });
    expect(result.perFileStats.size).toBe(0);
  });

  it("returns zero stats for whitespace-only input", () => {
    const result = parseGitNumstat("  \n  \n  ");
    expect(result.stats.filesCount).toBe(0);
    expect(result.perFileStats.size).toBe(0);
  });

  it("parses a single file with normal add/remove", () => {
    const stdout = "5\t3\tsrc/index.ts\n";
    const result = parseGitNumstat(stdout);
    expect(result.stats).toEqual({
      filesCount: 1,
      linesAdded: 5,
      linesRemoved: 3,
    });
    expect(result.perFileStats.size).toBe(1);
    const fileStat = result.perFileStats.get("src/index.ts");
    expect(fileStat).toEqual({
      added: 5,
      removed: 3,
      isBinary: false,
    });
  });

  it("sums add/remove across multiple files", () => {
    const stdout = [
      "10\t2\tsrc/a.ts",
      "5\t8\tsrc/b.ts",
      "0\t1\tsrc/c.ts",
    ].join("\n");
    const result = parseGitNumstat(stdout);
    expect(result.stats).toEqual({
      filesCount: 3,
      linesAdded: 15,
      linesRemoved: 11,
    });
    expect(result.perFileStats.size).toBe(3);
  });

  it("handles zero add and zero remove", () => {
    const stdout = "0\t0\tsrc/empty.ts\n";
    const result = parseGitNumstat(stdout);
    expect(result.stats).toEqual({
      filesCount: 1,
      linesAdded: 0,
      linesRemoved: 0,
    });
    const fileStat = result.perFileStats.get("src/empty.ts");
    expect(fileStat).toEqual({
      added: 0,
      removed: 0,
      isBinary: false,
    });
  });

  it("marks file as binary when add column is '-'", () => {
    const stdout = "-\t-\tassets/logo.png\n";
    const result = parseGitNumstat(stdout);
    expect(result.stats.filesCount).toBe(1);
    expect(result.stats.linesAdded).toBe(0);
    expect(result.stats.linesRemoved).toBe(0);
    expect(result.perFileStats.get("assets/logo.png")).toEqual({
      added: 0,
      removed: 0,
      isBinary: true,
    });
  });

  it("marks file as binary when remove column is '-'", () => {
    const stdout = "100\t-\tassets/icon.bin\n";
    const result = parseGitNumstat(stdout);
    expect(result.stats.filesCount).toBe(1);
    expect(result.stats.linesRemoved).toBe(0);
    expect(result.perFileStats.get("assets/icon.bin")!.isBinary).toBe(true);
  });

  it("handles files with tabs in names (3-part split with tabs)", () => {
    // A file path that contains tabs — parts[2] and beyond are joined
    const stdout = "1\t2\tfile\twith\ttabs.ts\n";
    const result = parseGitNumstat(stdout);
    expect(result.stats.filesCount).toBe(1);
    // The full path should be preserved with tabs
    expect(result.perFileStats.has("file\twith\ttabs.ts")).toBe(true);
    expect(result.perFileStats.get("file\twith\ttabs.ts")).toEqual({
      added: 1,
      removed: 2,
      isBinary: false,
    });
  });

  it("caps perFileStats at MAX_FILES (50)", () => {
    const lines: string[] = [];
    for (let i = 0; i < 60; i++) {
      lines.push(`1\t0\tfile${i}.ts`);
    }
    const stdout = lines.join("\n");
    const result = parseGitNumstat(stdout);
    // Total stats should count all 60 files
    expect(result.stats.filesCount).toBe(60);
    expect(result.stats.linesAdded).toBe(60);
    // But perFileStats should be capped at 50
    expect(result.perFileStats.size).toBe(50);
  });

  it("skips lines with less than 3 tab-separated parts", () => {
    const stdout = [
      "5\t3\tsrc/valid.ts",
      "incomplete\tline",
      "also-incomplete",
      "10\t0\tsrc/another.ts",
    ].join("\n");
    const result = parseGitNumstat(stdout);
    expect(result.stats.filesCount).toBe(2);
    expect(result.perFileStats.size).toBe(2);
    expect(result.perFileStats.has("src/valid.ts")).toBe(true);
    expect(result.perFileStats.has("src/another.ts")).toBe(true);
  });

  it("handles large numbers for add/remove", () => {
    const stdout = "99999\t88888\tsrc/big-change.ts\n";
    const result = parseGitNumstat(stdout);
    expect(result.stats.linesAdded).toBe(99999);
    expect(result.stats.linesRemoved).toBe(88888);
  });

  it("handles non-numeric add/remove values (eg, '-') correctly in sums", () => {
    const stdout = [
      "10\t5\tsrc/normal.ts",
      "-\t-\tassets/binary.png",
      "3\t1\tsrc/small.ts",
    ].join("\n");
    const result = parseGitNumstat(stdout);
    // Binary files contribute 0 to the total
    expect(result.stats.linesAdded).toBe(13);
    expect(result.stats.linesRemoved).toBe(6);
    expect(result.stats.filesCount).toBe(3);
  });

  it("handles trailing newlines", () => {
    const stdout = "1\t2\tsrc/file.ts\n\n";
    const result = parseGitNumstat(stdout);
    expect(result.stats.filesCount).toBe(1);
  });
});

