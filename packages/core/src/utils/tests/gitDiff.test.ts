/** Configure a mocked git command response */
function setGitResponse(
  args: string[],
  stdout: string,
  code = 0
): void {
  mockGitResponses.set(args.join(" "), { stdout, code });
}

/** Configure mocked access() result for a path */
function setAccessResult(path: string, exists: boolean): void {
  mockAccessResults.set(path, exists);
}

/** Reset all mock state */
function resetMocks(): void {
  mockGitResponses.clear();
  mockAccessResults.clear();
}

