describe("fetchGitDiffHunks", () => {
  const cwdMock = "/test/repo";

  it("returns empty Map when not in a git repo", async () => {
    setGitResponse(
      ["rev-parse", "--is-inside-work-tree"],
      "fatal: not a git repository",
      128
    );

    const result = await fetchGitDiffHunks(cwdMock);
    expect(result).toBeInstanceOf(Map);
    expect(result.size).toBe(0);
  });

  it("returns empty Map when in transient state", async () => {
    setGitResponse(
      ["rev-parse", "--is-inside-work-tree"],
      "true",
      0
    );
    setGitResponse(
      ["rev-parse", "--git-dir"],
      ".git",
      0
    );
    setAccessResult(`${cwdMock}/.git/MERGE_HEAD`, true);

    const result = await fetchGitDiffHunks(cwdMock);
    expect(result).toBeInstanceOf(Map);
    expect(result.size).toBe(0);
  });

  it("returns empty Map when diff command fails", async () => {
    setGitResponse(
      ["rev-parse", "--is-inside-work-tree"],
      "true",
      0
    );
    setGitResponse(
      ["rev-parse", "--git-dir"],
      ".git",
      0
    );
    // No transient files
    // diff HEAD fails
    setGitResponse(
      ["--no-optional-locks", "diff", "HEAD"],
      "fatal: something went wrong",
      128
    );

    const result = await fetchGitDiffHunks(cwdMock);
    expect(result).toBeInstanceOf(Map);
    expect(result.size).toBe(0);
  });

  it("returns hunks for normal diff", async () => {
    setGitResponse(
      ["rev-parse", "--is-inside-work-tree"],
      "true",
      0
    );
    setGitResponse(
      ["rev-parse", "--git-dir"],
      ".git",
      0
    );
    // No transient files
    setGitResponse(
      ["--no-optional-locks", "diff", "HEAD"],
      [
        "diff --git a/src/a.ts b/src/a.ts",
        "--- a/src/a.ts",
        "+++ b/src/a.ts",
        "@@ -1,3 +1,4 @@",
        " context",
        "-old",
        "+new",
        " more context",
      ].join("\n"),
      0
    );

    const result = await fetchGitDiffHunks(cwdMock);
    expect(result.size).toBe(1);
    const hunks = result.get("src/a.ts");
    expect(hunks).toBeDefined();
    expect(hunks!.length).toBe(1);
  });

  it("parses multiple files from diff output", async () => {
    setGitResponse(
      ["rev-parse", "--is-inside-work-tree"],
      "true",
      0
    );
    setGitResponse(
      ["rev-parse", "--git-dir"],
      ".git",
      0
    );
    setGitResponse(
      ["--no-optional-locks", "diff", "HEAD"],
      [
        "diff --git a/src/a.ts b/src/a.ts",
        "--- a/src/a.ts",
        "+++ b/src/a.ts",
        "@@ -1,2 +1,2 @@",
        " line1",
        "-old2",
        "+new2",
        "diff --git a/src/b.ts b/src/b.ts",
        "--- a/src/b.ts",
        "+++ b/src/b.ts",
        "@@ -10,3 +10,4 @@",
        " context",
        "-removed",
        "+added",
        " more",
      ].join("\n"),
      0
    );

    const result = await fetchGitDiffHunks(cwdMock);
    expect(result.size).toBe(2);
    expect(result.has("src/a.ts")).toBe(true);
    expect(result.has("src/b.ts")).toBe(true);
  });
});
